create table if not exists public.chat_sessions (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    title text not null default 'New conversation',
    legacy_chat_id text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index if not exists chat_sessions_user_legacy_unique
    on public.chat_sessions(user_id, legacy_chat_id)
    where legacy_chat_id is not null;

create index if not exists chat_sessions_user_updated_idx
    on public.chat_sessions(user_id, updated_at desc);

create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    chat_id uuid not null references public.chat_sessions(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    created_at timestamptz not null default now()
);

create index if not exists chat_messages_chat_created_idx
    on public.chat_messages(chat_id, created_at asc);

alter table public.chat_sessions enable row level security;
alter table public.chat_messages enable row level security;

-- A signed-in user can access only their own chat sessions.
drop policy if exists "Users manage their own chat sessions" on public.chat_sessions;
create policy "Users manage their own chat sessions"
    on public.chat_sessions
    for all
    to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

-- A signed-in user can access only messages belonging to their own account.
drop policy if exists "Users manage their own chat messages" on public.chat_messages;
create policy "Users manage their own chat messages"
    on public.chat_messages
    for all
    to authenticated
    using (
        auth.uid() = user_id
        and exists (
            select 1 from public.chat_sessions s
            where s.id = chat_id and s.user_id = auth.uid()
        )
    )
    with check (
        auth.uid() = user_id
        and exists (
            select 1 from public.chat_sessions s
            where s.id = chat_id and s.user_id = auth.uid()
        )
    );

-- No service-role key is used by CodeIt. RLS protects each account's data.
